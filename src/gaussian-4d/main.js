function halfToFloat32Array(u16) {
    // Convert an fp16 (IEEE 754 half) Uint16Array to Float32Array.
    // Handles subnormals and inf/nan; matches DataView.getFloat16 semantics.
    const out = new Float32Array(u16.length);
    for (let i = 0; i < u16.length; i++) {
        const h = u16[i];
        const sign = (h & 0x8000) >> 15;
        const exp = (h & 0x7c00) >> 10;
        const frac = h & 0x03ff;
        let val;
        if (exp === 0) {
            // subnormal or zero
            val = (frac === 0)
                ? 0
                : Math.pow(2, -14) * (frac / 1024);
        } else if (exp === 31) {
            val = frac === 0 ? Infinity : NaN;
        } else {
            val = Math.pow(2, exp - 15) * (1 + frac / 1024);
        }
        out[i] = sign ? -val : val;
    }
    return out;
}

